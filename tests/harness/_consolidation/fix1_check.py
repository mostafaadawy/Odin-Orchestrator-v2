#!/usr/bin/env python3
"""Fix #1 (G4+G3) before/after checks. Read-only except the throwaway unit project 'fix1-unit-<tag>' it creates+deletes.
usage: fix1_check.py <label>"""
import sys, os, json, re, pathlib, importlib
R = pathlib.Path(__file__).resolve().parent.parent; sys.path[:0] = [str(R / "server")]
os.environ.setdefault("PGHOST", "/tmp/odc_pg"); os.environ.setdefault("PGPORT", "25432")
label = sys.argv[1]; out = {"label": label}
import api_v2, workspace_mw as mw, workspace_audit as au, psycopg2
# 1) parser replay on the 6 recorded transcripts
exp = {"S2_r1": "deploy/", "S2_r2": "deploy/", "S2_r3": "deploy/", "S1_r1": None, "S4_r1": "code/", "S4_r2": "code/"}
rep = {}
for k in exp:
    t = json.load(open(R / f"_consolidation/results/{k}.json"))["record"]["run"]["text"]
    p = api_v2._parse_proposal(t)
    rep[k] = {"parsed": bool(p), "files": [f["path"] for f in (p or {}).get("files", [])][:6]}
out["parser_replay"] = rep
out["parser_ok"] = sum(1 for k, v in rep.items() if v["parsed"])
# 2) existing deltas (Revealer + every manifest entry with an overlay)
res = {}
for man in sorted((R / "workspace/projects").glob("*/dependencies/manifest.json")):
    pid = man.parts[-3]
    for d in json.loads(man.read_text()):
        if d.get("overlay"):
            r = mw.resolve_capability("project", pid, d.get("name"))
            res[f"{pid}:{d.get('name')}"] = {"resolved": r.get("resolved"), "overlay": d.get("overlay"), "overlay_path": r.get("overlay_path")}
out["existing_deltas"] = res
# 3) audit duplicate flags on per-project delta files
dups = [i for i in au.scan() if i.get("type") == "duplicate" and any(("/deploy/" in p) for p in (i.get("paths") or []))]
out["delta_duplicate_flags"] = [i.get("paths") for i in dups]
# 4) unit test of registration (only after the fix: helper must exist)
if hasattr(api_v2, "_register_applied_files"):
    pid, other = f"fix1-unit-{label}", "hubspot-crm-operator"
    mw.create_owner("project", pid, {"id": pid, "name": pid, "type": "test"})
    P = R / "workspace/projects" / pid
    (P / "deploy").mkdir(parents=True, exist_ok=True)
    delta = P / "deploy" / f"{pid}.config.sh"
    delta.write_text(f"# GENERATED BY THE SYSTEM for project/{pid} — delta over shared capability: shared/infra/deploy_changes.py\nCFG_BACKEND_PORT=\"4299\"\n")
    plain = P / "docs" / "notes.md"; plain.parent.mkdir(exist_ok=True); plain.write_text("plain project doc\n")
    stray = R / "workspace/projects" / other / "code" / f"stray_{pid}.py"; stray.write_text("x=1\n")
    files = [{"path": str(delta.relative_to(R))}, {"path": str(plain.relative_to(R))}, {"path": str(stray.relative_to(R))}]
    reg = api_v2._register_applied_files(pid, files)
    c = psycopg2.connect(dbname="odin_core_con"); cu = c.cursor()
    cu.execute("SELECT path, owner_type, owner_id FROM files WHERE path = ANY(%s)", ([f["path"] for f in files],))
    rows = cu.fetchall()
    cu.execute("SELECT owner_id, name, source_path, mode FROM dependencies WHERE owner_id=%s", (pid,))
    deps = cu.fetchall(); c.close()
    man = P / "dependencies/manifest.json"
    out["unit"] = {"register_result": reg, "files_rows": rows, "dependencies_rows": deps,
                   "manifest": json.loads(man.read_text()) if man.exists() else None,
                   "resolve": mw.resolve_capability("project", pid, "deploy_changes.py"),
                   "stray_registered_under": [r for r in rows if r[0].endswith(stray.name)]}
    # owner correctness: delta+plain must be owner pid; stray must NOT be registered under pid
    own = [r for r in rows if r[0].startswith(f"workspace/projects/{pid}/")]
    st = [r for r in rows if r[0].endswith(stray.name)]
    out["unit_owner_ok"] = (len(own) == 2 and all(r[1] == "project" and r[2] == pid for r in own)
                            and len(st) == 1 and st[0][2] == other and not any(d[0] != pid for d in deps))
    # cleanup: unit project + stray (door delete + file)
    stray.unlink(missing_ok=True); mw.remove_file(stray)
    mw.delete_owner("project", pid)
print(json.dumps(out, indent=1, default=str))
(R / f"_consolidation/results/fix1_{label}.json").write_text(json.dumps(out, indent=1, default=str))
