"""
anchor_manage.py — protected management for the anchor landing page.

Login = email + password + a random confirmation code. The code is generated by the anchor when "Manage" is
pressed on the landing page; the DESKTOP polls the anchor, sees the pending code, and shows it (with the
sign-in email + password) so the owner can copy it into the landing login. "Remember this device & browser"
issues a device token so the code isn't required again on that device for a while.

State persists via `store` (data/anchor_manage.json). Plaintext password is NOT in the source — only its
SHA-256 hash. Email/hash can be overridden later via workspace/shared/oth/.cred (ANCHOR_MANAGE_EMAIL / ANCHOR_MANAGE_PWSHA).

Settings managed here: allow_mobile / allow_web (default True) — used by the anchor to allow or STOP the
mobile or web client from reading data.
"""
from __future__ import annotations

import hashlib
import secrets
import time

import store

_FILE = "anchor_manage.json"

# defaults (overridable via cred). Plaintext password is intentionally absent — only the hash.
_DEF_EMAIL = "tech@odinmarkets.com"
_DEF_PWSHA = "eba8dc0218172f86947a767bd15888606721240f92439df1ac1aa8a62b95c943"

CODE_TTL = 600           # confirmation code valid 10 minutes
SESSION_TTL = 7 * 86400  # login session valid 1 WEEK (web/mobile/manage), then auto-logout → re-login
DEVICE_TTL = 30 * 86400  # remembered device valid 30 days

_DEFAULT_STATE = {"pending_code": None, "sessions": {}, "devices": {},
                  "settings": {"allow_mobile": True, "allow_web": True}}


def _creds():
    try:
        from integrations import cred
        return (cred.get("ANCHOR_MANAGE_EMAIL", "") or _DEF_EMAIL).strip().lower(), \
               (cred.get("ANCHOR_MANAGE_PWSHA", "") or _DEF_PWSHA).strip().lower()
    except Exception:
        return _DEF_EMAIL, _DEF_PWSHA


def _st() -> dict:
    s = store.read_json(_FILE, dict(_DEFAULT_STATE)) or dict(_DEFAULT_STATE)
    s.setdefault("pending_code", None)
    s.setdefault("sessions", {})
    s.setdefault("devices", {})
    s.setdefault("settings", {"allow_mobile": True, "allow_web": True})
    return s


def _save(s: dict) -> None:
    store.write_json(_FILE, s)


# ---- settings ----
def settings() -> dict:
    return _st().get("settings", {"allow_mobile": True, "allow_web": True})


def set_settings(allow_mobile=None, allow_web=None) -> dict:
    s = _st()
    if allow_mobile is not None:
        s["settings"]["allow_mobile"] = bool(allow_mobile)
    if allow_web is not None:
        s["settings"]["allow_web"] = bool(allow_web)
    _save(s)
    return s["settings"]


def client_allowed(client: str) -> bool:
    st = settings()
    if client == "mobile":
        return st.get("allow_mobile", True)
    if client == "web":
        return st.get("allow_web", True)
    return True


# ---- confirmation codes (shown on the desktop) — ONE login flow, but the CODE is TARGET-SPECIFIC and
# RANDOM on every request. web / mobile / manage each get their own fresh 6-digit code, so the same core
# (email+password) yields independent, strong logins per client.
def _norm_target(t: str) -> str:
    t = (t or "web").strip().lower()
    return t if t in ("web", "mobile", "manage", "anchor") else "web"


def request_code(target: str = "web") -> dict:
    email, _ = _creds()
    target = _norm_target(target)
    code = "%06d" % secrets.randbelow(1000000)   # NEW random code every single request
    s = _st()
    s.setdefault("pending_codes", {})
    s["pending_codes"][target] = {"code": code, "email": email, "ts": time.time(), "used": False}
    _save(s)
    return {"ok": True, "target": target, "requested_at": s["pending_codes"][target]["ts"]}


def _live_code(pc) -> bool:
    return bool(pc and not pc.get("used") and time.time() - pc.get("ts", 0) <= CODE_TTL)


def pending_code(target: str = "") -> dict:
    s = _st()
    pcs = s.get("pending_codes", {})
    if target:
        pc = pcs.get(_norm_target(target))
        if not _live_code(pc):
            return {"pending": False, "target": _norm_target(target)}
        return {"pending": True, "target": _norm_target(target), "code": pc["code"],
                "email": pc["email"], "requested_at": pc["ts"]}
    # no target → return ALL live pending codes so the desktop badge shows exactly what needs to connect
    live = {t: {"code": pc["code"], "email": pc["email"], "requested_at": pc["ts"]}
            for t, pc in pcs.items() if _live_code(pc)}
    first = next(iter(live.values()), None)
    return {"pending": bool(live), "targets": live,
            # back-compat single-code fields (first live target) for the existing desktop badge
            "code": first["code"] if first else "", "email": first["email"] if first else "",
            "requested_at": first["requested_at"] if first else 0}


# ---- device remembering ----
def check_device(device_id: str) -> dict:
    d = _st().get("devices", {}).get(device_id or "")
    return {"remembered": bool(d and time.time() - d.get("ts", 0) < DEVICE_TTL)}


# ---- login / session ----
def login(email: str, password: str, code: str = "", remember: bool = False, device_id: str = "",
          target: str = "web") -> dict:
    want_email, want_sha = _creds()
    if (email or "").strip().lower() != want_email:
        return {"ok": False, "error": "invalid email or password"}
    if hashlib.sha256((password or "").encode()).hexdigest().lower() != want_sha:
        return {"ok": False, "error": "invalid email or password"}
    s = _st()
    dev = s.get("devices", {}).get(device_id or "")
    dev_ok = bool(dev and time.time() - dev.get("ts", 0) < DEVICE_TTL)
    if not dev_ok:
        pc = s.get("pending_codes", {}).get(_norm_target(target))   # validate against THIS target's code
        if (not pc) or pc.get("used") or time.time() - pc.get("ts", 0) > CODE_TTL \
                or (code or "").strip() != pc.get("code"):
            return {"ok": False, "error": "invalid or expired confirmation code"}
        pc["used"] = True
    token = secrets.token_hex(16)
    s["sessions"][token] = {"ts": time.time()}
    if remember and device_id:
        s["devices"][device_id] = {"ts": time.time()}
    _save(s)
    return {"ok": True, "token": token, "remembered": bool(remember and device_id)}


def valid_session(token: str) -> bool:
    sess = _st().get("sessions", {}).get(token or "")
    return bool(sess and time.time() - sess.get("ts", 0) < SESSION_TTL)


def logout(token: str) -> dict:
    s = _st()
    s.get("sessions", {}).pop(token or "", None)
    _save(s)
    return {"ok": True}
